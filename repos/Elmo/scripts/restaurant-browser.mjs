	await expect(page.getByRole("heading", { name: "门店资料工作台" })).toBeVisible();
	await page.waitForFunction(() => Array.from(document.querySelectorAll("button")).some((button) => button.textContent === "新建门店" && Object.keys(button).some((key) => key.startsWith("__reactProps$") && typeof button[key].onClick === "function")));
	checks.push("authenticated workbench loads");
