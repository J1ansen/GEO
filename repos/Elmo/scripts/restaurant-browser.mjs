	await page.getByRole("button", { name: "资料与确认", exact: true }).click();
	for (const label of ["门店名称", "地址与时区"]) await section(label).getByLabel("填写此项资料").check();
	await page.getByLabel("英文／对外店名").fill("Sample Cafe");
	await page.getByLabel("街道地址").fill("1 Example Street");
	await page.getByLabel("城市", { exact: true }).fill("New York");
